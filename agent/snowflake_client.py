"""Snowflake side of the agent.

ask_metrics    -> Snowflake managed MCP server (Cortex Analyst writes SQL from the semantic view)
run_metric_sql -> Snowflake SQL API (executes that SQL; trial accounts block SYSTEM_EXECUTE_SQL)

Both use the same PAT, so the same network policy and the AGENT_READER role apply.
"""

import asyncio
import json
import logging
import os
import re
import time

import httpx
from dotenv import load_dotenv
from langchain_mcp_adapters.client import MultiServerMCPClient

# Load environment variables from a .env file (keeps secrets out of the codebase)
load_dotenv()  # reads .env into environment variables; never print these

# Initialize a dedicated logger for this module to track agent behavior and performance
log = logging.getLogger("agent.snowflake")  # LOG

# Setup Snowflake connection endpoints and authentication headers
ACCOUNT_URL = os.environ["SNOWFLAKE_ACCOUNT_URL"].rstrip("/")
MCP_URL = os.environ["SNOWFLAKE_MCP_URL"]
AUTH_HEADERS = {
    "Authorization": f"Bearer {os.environ['SNOWFLAKE_MCP_PAT']}",
    "X-Snowflake-Authorization-Token-Type": "PROGRAMMATIC_ACCESS_TOKEN",
}


# ---------- MCP (ask_metrics) ----------

def mcp_client() -> MultiServerMCPClient:
    """MCP client pointed at our Snowflake managed MCP server."""
    # Log connection attempts without exposing sensitive token values
    log.info("MCP -> %s", MCP_URL)                                     # LOG
    log.debug("Auth header names: %s", list(AUTH_HEADERS))             # LOG (names only, never values)

    # Configure LangChain to communicate with Snowflake's MCP server over HTTP
    return MultiServerMCPClient({
        "snowflake_metrics": {
            "transport": "streamable_http",
            "url": MCP_URL,
            "headers": AUTH_HEADERS,
        }
    })


def tool_text(result) -> str:
    """MCP tool results can be a string or a list of content blocks; return plain text."""
    log.debug("Raw tool result type: %s", type(result).__name__)       # LOG

    # Extract the actual text content regardless of how the MCP tool formats its response
    if isinstance(result, tuple):          # (content, artifact) form
        result = result[0]
    if isinstance(result, str):
        return result

    items = result if isinstance(result, list) else [result]
    return "".join(i.get("text", "") if isinstance(i, dict) else getattr(i, "text", str(i)) for i in items)


def parse_analyst(text: str) -> dict:
    """Cortex Analyst returns [{"text": interpretation}, {"statement": sql, ...}]."""
    log.debug("Cortex Analyst raw text: %s", text)                     # LOG

    # Safely parse the JSON payload returned by Cortex Analyst
    try:
        items = json.loads(text)
    except json.JSONDecodeError:
        # If it fails to parse, Cortex Analyst likely gave a conversational response instead of SQL
        log.warning("Cortex Analyst returned non-JSON text (no SQL)")  # LOG
        return {"interpretation": text, "sql": None}

    # Extract the natural language interpretation of the query
    interpretation = " ".join(i["text"] for i in items if isinstance(i, dict) and "text" in i)
    # Extract the actual SQL statement generated by Cortex Analyst
    sql = next((i["statement"] for i in items if isinstance(i, dict) and i.get("statement")), None)

    # Log the outcome of the AI's translation attempt
    log.info("Cortex Analyst -> %s (interpretation %d chars)",         # LOG
             "SQL returned" if sql else "NO SQL (likely out of scope)", len(interpretation))
    log.debug("Generated SQL:\n%s", sql)                               # LOG

    return {"interpretation": interpretation, "sql": sql}


# ---------- Guard + SQL API (run_metric_sql) ----------

# Regular expressions for security checks to prevent SQL injection and unauthorized table access
_WRITE_WORDS = re.compile(
    r"\b(insert|update|delete|merge|create|drop|alter|grant|revoke|call|copy|put|truncate|use)\b", re.I)
_OTHER_TABLE = re.compile(r"\b(?:from|join)\s+(?!semantic_view\b)\w+\.\w+", re.I)
_SEMANTIC_VIEW = re.compile(r"semantic_view\s*\(\s*analytics\.semantic\.ecom_metrics\b", re.I)


def _block(reason: str) -> None:
    # Helper to log exactly why a query was blocked before raising the error
    log.warning("Guard BLOCKED: %s", reason)                           # LOG
    raise ValueError(reason)


def check_sql(sql: str) -> str:
    """Allow only single, read-only queries over the certified semantic view."""
    # Clean the query: remove SQL comments and trailing semicolons to simplify inspection
    body = re.sub(r"--[^\n]*", "", sql).strip().rstrip(";").strip()   # drop comments + trailing ;
    log.debug("Guard input (cleaned):\n%s", body)                     # LOG

    # Series of strict security checks. If any fail, trigger _block()
    if ";" in body:
        _block("Only one SQL statement is allowed.")
    if not re.match(r"^(select|with)\b", body, re.I):
        _block("Only SELECT queries are allowed.")
    if not _SEMANTIC_VIEW.search(body):
        _block("Query must read from the ECOM_METRICS semantic view.")
    if _OTHER_TABLE.search(body):
        _block("Query may only read from the semantic view, not other tables.")
    if _WRITE_WORDS.search(body):
        _block("Write/DDL keywords are not allowed.")

    # If it passed all checks, log success and return the safe query
    log.info("Guard PASSED (semantic view, read-only, single statement)")  # LOG
    return body


async def run_metric_sql(sql: str, timeout: int = 60) -> dict:
    """Run guarded SQL through the Snowflake SQL API as AGENT_READER."""
    # First, run the SQL through our security guardrails
    body = check_sql(sql)

    # Prepare the payload for the Snowflake REST API
    payload = {"statement": body, "warehouse": "REPORTING", "role": "AGENT_READER", "timeout": timeout}
    headers = {**AUTH_HEADERS, "Accept": "application/json"}

    log.info("SQL API POST /api/v2/statements (warehouse=REPORTING, role=AGENT_READER)")  # LOG
    start = time.perf_counter()                                         # LOG

    # Use httpx for asynchronous HTTP requests
    async with httpx.AsyncClient(base_url=ACCOUNT_URL, headers=headers, timeout=timeout + 10) as http:
        # Submit the query for execution
        r = await http.post("/api/v2/statements", json=payload)

        # Snowflake API returns 202 if the query is still executing. Poll until it finishes.
        while r.status_code == 202:                      # still running -> poll
            handle = r.json()["statementHandle"]
            log.info("SQL API still running, polling %s", handle)    # LOG
            await asyncio.sleep(1)
            # Fetch the updated status using the statement handle
            r = await http.get(f"/api/v2/statements/{handle}")

        # If we didn't get a 200 OK, something went wrong during execution
        if r.status_code != 200:
            try:
                msg = r.json().get("message")
            except ValueError:
                msg = r.text
            log.error("SQL API failed: %s %s", r.status_code, msg)   # LOG
            raise RuntimeError(f"Snowflake error {r.status_code}: {msg}")

        res = r.json()

    # Extract column names and map them to the returned data rows
    columns = [c["name"] for c in res["resultSetMetaData"]["rowType"]]

    # Log the successful execution details (row count, time taken, and query ID)
    log.info("SQL API done: %d row(s) in %.2fs, query_id=%s",        # LOG
             len(res["data"]), time.perf_counter() - start, res.get("statementHandle"))

    return {"columns": columns, "rows": res["data"]}
